<!-- This is the home view - which shows a dashboard -->
<template>
  <main>
    <div>
      <h1 class="font-bold text-4xl text-red-700 tracking-widest text-center mt-10">
        Dashboard
      </h1>
      <br />
      <div class="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-4 gap-x-6 gap-y-10">
        <div class="ml-10"></div>
        <div class="flex flex-col col-span-2">
          <h1 class="font-bold text-4xl text-red-700 tracking-widest text-center mt-10">
              Events Attendance
          </h1>
      
          <div v-if="!recentEvents.length" class="flex justify-center mt-10">No events found.</div>
          <table v-if="recentEvents.length" class="min-w-full shadow-md rounded">
            <thead class="bg-gray-50 text-xl">
              <tr class="p-4 text-left">
                <th class="p-4 text-left">Event Name</th>
                <th class="p-4 text-left">Event Date</th>
                <th class="p-4 text-left">Number of Attendees</th>
              </tr>
            </thead>
            <tbody class="divide-y divide-gray-300"> 
              <tr
                @click="editEvent(event._id)"
                v-for="event in recentEvents"
                :key="event._id"
              >
                <td class="p-2 text-left">{{ event.name }}</td>
                <td class="p-2 text-left">{{ formatDate(event.date) }}</td>
                <td class="p-2 text-left">{{ event.attendees.length }}</td>
              </tr>
            </tbody>
          </table>
          
          <div v-if="recentEvents.length">
            <AttendanceChart
              v-if="!loading && !error"
              :label="labels"
              :chart-data="chartData"
            ></AttendanceChart>

            <!-- Start of loading animation -->
            <div class="mt-40" v-if="loading">
              <p
                class="text-6xl font-bold text-center text-gray-500 animate-pulse"
              >
                Loading...
              </p>
            </div>
            <!-- End of loading animation -->

            <!-- Start of error alert -->
            <div class="mt-12 bg-red-50" v-if="error">
              <h3 class="px-4 py-1 text-4xl font-bold text-white bg-red-800">
                {{ error.title }}
              </h3>
              <p class="p-4 text-lg font-bold text-red-900">
                {{ error.message }}
              </p>
            </div>
            <!-- End of error alert -->
          </div>
        </div>
      </div>
      <div class="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-4 gap-x-6 gap-y-10">
        <div class="ml-10"></div>
        <div class="flex flex-col col-span-2">
          <h1 class="font-bold text-4xl text-red-700 tracking-widest text-center mt-10">
              Clients by Zip Code
          </h1>
          
          <div v-if="!zips.length" class="flex justify-center mt-10">No clients found.</div>
          <table v-if="zips.length" class="min-w-full shadow-md rounded">
            <thead class="bg-gray-50 text-xl">
              <tr class="p-4 text-left">
                <th class="p-4 text-left">Zip Number</th>
                <th class="p-4 text-left">Client Count</th>
              </tr>
            </thead>
            <tbody class="divide-y divide-gray-300">
              <tr
                v-for="zip in zips"
                :key="zip._id"
              >
                <td class="p-2 text-left">{{ zip._id }}</td>
                <td class="p-2 text-left">{{ zip.count }}</td>
              </tr>
            </tbody>
          </table>
          <div v-if="zips.length" class="flex justify-center mt-10">
            <ZipChart
              v-if="!zipLoading && !zipError"
              :label="zipLabels"
              :chart-data="zipChartData"
            ></ZipChart>

            <!-- Start of loading animation -->
            <div class="mt-40" v-if="zipLoading">
              <p
                class="text-6xl font-bold text-center text-gray-500 animate-pulse"
              >
                Loading...
              </p>
            </div>
            <!-- End of loading animation -->

            <!-- Start of error alert -->
            <div class="mt-12 bg-red-50" v-if="zipError">
              <h3 class="px-4 py-1 text-4xl font-bold text-white bg-red-800">
                {{ zipError.title }}
              </h3>
              <p class="p-4 text-lg font-bold text-red-900">
                {{ zipError.message }}
              </p>
            </div>
            <!-- End of error alert -->
          </div>
        </div>
      </div>
    </div>
  </main>
</template>

<script setup>
// MIGRATION NOTE: Converted from the Options API (components, data, mounted, methods) to <script setup>.
import { ref, onMounted } from 'vue'
import { useRouter } from 'vue-router'
// MIGRATION NOTE: the `components: {}` option is gone. In <script setup>, an imported
// component can be used in the template right away under the name it was imported as.
import AttendanceChart from '../components/barChart.vue'
import ZipChart from '../components/donutZipChart.vue'
import { getAttendance, getClientsByZipCode } from '../api/api'

const router = useRouter()

// MIGRATION NOTE: each property in the data option became its own ref
const recentEvents = ref([])
const zips = ref([])
const labels = ref([])
const chartData = ref([])
const zipLabels = ref([])
const zipChartData = ref([])
// Loading flags start as true because both requests begin as soon as the page mounts.
// (They started as false before, which let the chart's v-if pass for a moment before data arrived.)
const loading = ref(true)
const error = ref(null)
const zipLoading = ref(true)
const zipError = ref(null)

// Turns a caught error into the { title, message } shape the template's error alert expects.
// The same if/else chain was copy-pasted in both data-loading methods before; now it lives once.
function toErrorAlert(err) {
  if (err.response) {
    // client received an error response (5xx, 4xx)
    return { title: 'Server Response', message: err.message }
  } else if (err.request) {
    // client never received a response, or request never left
    return { title: 'Unable to Reach Server', message: err.message }
  }
  // There's probably an error in your code
  return { title: 'Application Error', message: err.message }
}

// MIGRATION NOTE: methods.formatDate became a regular function
// function called to format the event date
function formatDate(date) {
  const isoDate = new Date(date)
  const year = isoDate.getUTCFullYear()
  const month = String(isoDate.getUTCMonth() + 1).padStart(2, '0')
  const day = String(isoDate.getUTCDate()).padStart(2, '0')
  return `${month}/${day}/${year}`
}

// MIGRATION NOTE: methods.getAttendanceData became a regular function. this.x became x.value
async function getAttendanceData() {
  try {
    error.value = null
    loading.value = true

    const attendance = await getAttendance()
    recentEvents.value = attendance
    labels.value = attendance.map((item) => `${item.name} (${formatDate(item.date)})`)
    chartData.value = attendance.map((item) => item.attendees.length)
  } catch (err) {
    error.value = toErrorAlert(err)
  }
  loading.value = false
}

// MIGRATION NOTE: methods.getZipData became a regular function
async function getZipData() {
  try {
    zipError.value = null
    zipLoading.value = true

    const zipdata = await getClientsByZipCode()
    zips.value = zipdata
    zipLabels.value = zipdata.map((item) => item._id)
    zipChartData.value = zipdata.map((item) => item.count)
  } catch (err) {
    zipError.value = toErrorAlert(err)
  }
  zipLoading.value = false
}

// MIGRATION NOTE: the template has always called editEvent(event._id) when a row is clicked,
// but the Options API version never defined it, so clicking a row threw an error in the console.
// It now opens that event's details page.
function editEvent(eventId) {
  router.push({ name: 'eventdetails', params: { id: eventId } })
}

// MIGRATION NOTE: mounted() became onMounted()
onMounted(() => {
  getAttendanceData()
  getZipData()
})
</script>
